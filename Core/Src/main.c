  g_fw.seat_pwm_duty    = 40u;
  g_fw.seat_duration_ms = 1000u;
  g_fw.seat_cmd_seq++;

#elif FW_TEST_CASE == 2u
  /* PARKING + PIR 시험 */
  g_fw.ignition_state  = IGN_OFF;
  g_fw.operation_state = OP_PARKING;
  g_fw.ignition_state  = IGN_OFF;
