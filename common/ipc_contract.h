#ifndef SCHOOL_BUS_IPC_CONTRACT_H
#define SCHOOL_BUS_IPC_CONTRACT_H

#include <stdint.h>

/*
 * RPi4 Central <-> Qt UI POSIX mqueue contract.
 *
 * Keep these numeric values fixed. The queue transfers raw integers, so if
 * Central and UI disagree on these numbers the screen will not change even
 * though messages are being sent.
 */
typedef enum
{
    IPC_MSG_NONE = 0,

    /* Qt UI -> RPi4 Central */
    IPC_MSG_BOARDING_BUTTON = 1,
    IPC_MSG_DRIVER_ID_RECEIVED = 2,

    /* RPi4 Central -> Qt UI */
    IPC_MSG_SHOW_AUTH_SCREEN = 3,
    IPC_MSG_SHOW_READY_SCREEN = 4,
    IPC_MSG_SHOW_OPERATION_SCREEN = 5,
    IPC_MSG_SHOW_BOARDING_SCREEN = 6,
    IPC_MSG_SCREEN_OFF = 7,
    IPC_MSG_AUTH_FAIL = 8,
    IPC_MSG_SEATBELT_UPDATE = 9,
    IPC_MSG_ENV_UPDATE = 10,
    IPC_MSG_CHILD_DETECTED_WARNING = 11,
    IPC_MSG_PROFILE_APPLIED = 12,
    IPC_MSG_DUST_UPDATE = 13,
    IPC_MSG_FW_STATUS_UPDATE = 14,
    IPC_MSG_ALARM_ACK = 15,
    IPC_MSG_IGNITION_BLOCKED_RESIDUAL_CHILD = 16,
    IPC_MSG_PIN_GENERATED = 17,
    IPC_MSG_FACE_AUTH_SUCCESS = 18,
    IPC_MSG_FACE_AUTH_FAIL = 19,

    IPC_MSG_MAX = 20,

    /* Compatibility names used by older PR code. */
    IPC_MSG_UI_BOARDING_BUTTON = IPC_MSG_BOARDING_BUTTON,
    IPC_MSG_UI_DRIVER_ID_INPUT = IPC_MSG_DRIVER_ID_RECEIVED,
    IPC_MSG_UI_FACE_AUTH_SUCCESS = IPC_MSG_FACE_AUTH_SUCCESS,
    IPC_MSG_UI_FACE_AUTH_FAIL = IPC_MSG_FACE_AUTH_FAIL,
    IPC_MSG_DRIVER_AUTH_SCREEN = IPC_MSG_SHOW_AUTH_SCREEN,
    IPC_MSG_AUTH_FAIL_SCREEN = IPC_MSG_AUTH_FAIL,
    IPC_MSG_WAIT_IGNITION_SCREEN = IPC_MSG_SHOW_READY_SCREEN,
    IPC_MSG_OPERATIONAL_SCREEN = IPC_MSG_SHOW_OPERATION_SCREEN,
    IPC_MSG_PASSENGER_TRANSFER_SCREEN = IPC_MSG_SHOW_BOARDING_SCREEN,
    IPC_MSG_SHUTDOWN_SCREEN = IPC_MSG_SCREEN_OFF,
    IPC_MSG_SEATBELT_UI_UPDATE = IPC_MSG_SEATBELT_UPDATE
} IpcMessageType;

typedef struct
{
    int32_t type;
    int32_t data[4];
} IpcMessage;

#define IPC_QT_TO_CENTRAL_QUEUE_DEFAULT "/qt_to_central"
#define IPC_CENTRAL_TO_QT_QUEUE_DEFAULT "/central_to_qt"
#define IPC_QT_TO_CENTRAL_QUEUE_ENV "QT_TO_CENTRAL_QUEUE"
#define IPC_CENTRAL_TO_QT_QUEUE_ENV "CENTRAL_TO_QT_QUEUE"
#define IPC_QUEUE_MAX_MESSAGES_DEFAULT 10L

#endif
